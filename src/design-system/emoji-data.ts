export const ALL_EMOJIS: Emoji[] = EMOJI_CATEGORIES.flatMap((c) => c.emojis);

const byChar = new Map(ALL_EMOJIS.map((e) => [e.char, e]));
export const findEmoji = (char: string) => byChar.get(char);

/** Busca sem acento e sem diferenciar maiúsculas. */
const fold = (text: string) => text.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();
export function searchEmojis(query: string): Emoji[] {
  const q = fold(query.trim());
  return q ? ALL_EMOJIS.filter((e) => fold(e.name).includes(q)) : [];
}
